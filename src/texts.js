  var overrides = {};

  function plural(n, forms) {
    n = Math.abs(Math.floor(Number(n) || 0));
    var a = n % 10, b = n % 100;
    if (a === 1 && b !== 11) return forms[0];
    if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return forms[1] !== undefined ? forms[1] : forms[0];
    return forms[2] !== undefined ? forms[2] : forms[forms.length - 1];
  }

  function render(tpl, vars) {
    vars = vars || {};
    return String(tpl).replace(/\{([A-Za-zА-Яа-я0-9_]+)(?::([^}]*))?\}/g, function (m, name, forms) {
      if (!(name in vars)) return m;
      if (forms !== undefined) return plural(vars[name], forms.split('|'));
      var v = vars[name];
      return v === null || v === undefined ? '' : String(v);
    });
  }

